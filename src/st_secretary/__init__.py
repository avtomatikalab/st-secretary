"""СТ-Секретарь — система для секретариата и судей соревнований по спортивному туризму.

Ядро (этот пакет) не зависит от интернета и не использует ИИ для расчётов: все результаты,
места, ранги и нормативы вычисляются по правилам и проверяются тестами на реальных протоколах.
"""

__version__ = "0.5.1"

# Стадия (Правки, п. 42): «бета» — весь путь секретаря есть, его проверяют на настоящих соревнованиях. В номер версии
# пометку НЕ дописывать: updates.parse_version не поймёт «0.4.0-beta» (обновление его не увидит), а выпуск, отмеченный
# на GitHub как pre-release, пропадёт из releases/latest вместе со ссылками «Скачать». Пусто — пометки нет (к 1.0).
STAGE = "бета"


def version_label(version: str = __version__) -> str:
    """Версия для людей — с пометкой стадии: «0.4.0 бета» (подвал страниц, журнал, инструкция)."""
    return f"{version} {STAGE}".strip()
