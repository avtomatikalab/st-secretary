"""Суммы прописью — для договоров и актов."""

import pytest

from st_secretary.money import money, number_words, rubles_text


@pytest.mark.parametrize("n, words", [
    (0, "ноль"), (1, "один"), (12, "двенадцать"), (21, "двадцать один"), (100, "сто"), (215, "двести пятнадцать"),
    (1000, "одна тысяча"), (1350, "одна тысяча триста пятьдесят"), (1725, "одна тысяча семьсот двадцать пять"),
    (2520, "две тысячи пятьсот двадцать"), (4250, "четыре тысячи двести пятьдесят"),
    (11364, "одиннадцать тысяч триста шестьдесят четыре"), (37880, "тридцать семь тысяч восемьсот восемьдесят"),
    (49244, "сорок девять тысяч двести сорок четыре"), (101000, "сто одна тысяча"),
    (2000001, "два миллиона один"),
])
def test_number_words(n, words):
    assert number_words(n) == words


def test_rubles_and_money():
    assert rubles_text(4250) == "4250 (четыре тысячи двести пятьдесят) рублей 00 копеек"
    assert rubles_text(1841) == "1841 (одна тысяча восемьсот сорок один) рубль 00 копеек"
    assert rubles_text(2.5) == "2 (два) рубля 50 копеек"
    assert money(4250) == "4 250,00" and money(850) == "850,00" and money(49244.5) == "49 244,50"
