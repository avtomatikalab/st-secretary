"""Профили дисциплин: как из данных дистанции получается результат и место."""

from enum import Enum


class Status(Enum):
    """Итоговый статус участника (связки, группы, команды) на дистанции."""

    FINISHED = "finished"  # прошёл дистанцию, результат определён
    REMOVED = "removed"  # снят с дистанции / соревнований
    DNF = "dnf"  # не финишировал
    OVER_TIME = "over_time"  # превысил контрольное время дистанции
    DNS = "dns"  # не стартовал
    OUT_OF_COMPETITION = "ooc"  # вне конкурса
