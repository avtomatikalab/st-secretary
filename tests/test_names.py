"""Склонение ФИО в дательный падеж — для справок о судействе («Дана Иванову Ивану Ивановичу»)."""

import pytest

from st_secretary.names import dative, guess_sex, he_she


@pytest.mark.parametrize("fio, expected", [
    ("Иванов Иван Иванович", "Иванову Ивану Ивановичу"),
    ("Иванова Анна Сергеевна", "Ивановой Анне Сергеевне"),
    ("Кузнецова Ульяна Андреевна", "Кузнецовой Ульяне Андреевне"),
    ("Бельский Андрей Ильич", "Бельскому Андрею Ильичу"),
    ("Толстая Мария Олеговна", "Толстой Марии Олеговне"),
    ("Шевченко Игорь Петрович", "Шевченко Игорю Петровичу"),
    ("Черных Любовь Ивановна", "Черных Любови Ивановне"),
    ("Бурмага Виктор Александрович", "Бурмаге Виктору Александровичу"),
    ("Бурмага Анна Викторовна", "Бурмаге Анне Викторовне"),
    ("Демкина Лидия Демьяновна", "Демкиной Лидии Демьяновне"),
    ("Никитин Никита Ильич", "Никитину Никите Ильичу"),
    ("Кузьмич Анна Петровна", "Кузьмич Анне Петровне"),
    ("Гайдай Леонид Иович", "Гайдаю Леониду Иовичу"),
    ("Мамедов Али Мамед оглы", "Мамедову Али Мамед оглы"),
])
def test_dative(fio, expected):
    assert dative(fio) == expected


def test_sex():
    assert guess_sex("Орлов Павел Ильич") == "м" and guess_sex("Орлова Павла Ильинична") == "ж"
    assert guess_sex("Лис Ева") == "ж" and guess_sex("Сом Илья") == "м"
    assert he_she("ж") == ("она", "участвовала") and he_she("м") == ("он", "участвовал")
